//! The sidebar beside an issue or pull request: assignees, labels, milestone,
//! notifications and deletion.
use super::super::fallback::{MessageFamily, MessageWriter};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum IssueSidebarMessage {
    Assignees,
    NoOne,
    AssignYourself,
    EditAssignees,
    SaveAssignees,
    Labels,
    NoneYet,
    EditLabels,
    NoRepositoryLabels,
    SaveLabels,
    Milestone,
    NoMilestone,
    ChangeMilestone,
    SaveMilestone,
    Notifications,
    Subscribe,
    Unsubscribe,
    NotNotifiedIssue,
    NotNotifiedPull,
    /// The accessible name of the delete section.
    Danger,
    DeleteIssue,
    DeletePull,
    DeleteIssueConfirm,
    DeletePullConfirm,
    /// Why the viewer is notified about the thread.
    ReasonManual,
    ReasonComment,
    ReasonReviewed,
    ReasonAuthor,
    ReasonMention,
    ReasonAssigned,
    ReasonReviewRequested,
}

impl MessageFamily for IssueSidebarMessage {
    fn id(self) -> &'static str {
        match self {
            Self::Assignees => "issues.sidebar.assignees",
            Self::NoOne => "issues.sidebar.no-one",
            Self::AssignYourself => "issues.sidebar.assign-yourself",
            Self::EditAssignees => "issues.sidebar.edit-assignees",
            Self::SaveAssignees => "issues.sidebar.save-assignees",
            Self::Labels => "issues.sidebar.labels",
            Self::NoneYet => "issues.sidebar.no-labels",
            Self::EditLabels => "issues.sidebar.edit-labels",
            Self::NoRepositoryLabels => "issues.sidebar.no-repository-labels",
            Self::SaveLabels => "issues.sidebar.save-labels",
            Self::Milestone => "issues.sidebar.milestone",
            Self::NoMilestone => "issues.sidebar.no-milestone",
            Self::ChangeMilestone => "issues.sidebar.change-milestone",
            Self::SaveMilestone => "issues.sidebar.save-milestone",
            Self::Notifications => "issues.sidebar.notifications",
            Self::Subscribe => "issues.sidebar.subscribe",
            Self::Unsubscribe => "issues.sidebar.unsubscribe",
            Self::NotNotifiedIssue => "issues.sidebar.not-notified-issue",
            Self::NotNotifiedPull => "issues.sidebar.not-notified-pull",
            Self::Danger => "issues.sidebar.danger",
            Self::DeleteIssue => "issues.sidebar.delete-issue",
            Self::DeletePull => "issues.sidebar.delete-pull",
            Self::DeleteIssueConfirm => "issues.sidebar.delete-issue-confirm",
            Self::DeletePullConfirm => "issues.sidebar.delete-pull-confirm",
            Self::ReasonManual => "issues.sidebar.reason.manual",
            Self::ReasonComment => "issues.sidebar.reason.comment",
            Self::ReasonReviewed => "issues.sidebar.reason.reviewed",
            Self::ReasonAuthor => "issues.sidebar.reason.author",
            Self::ReasonMention => "issues.sidebar.reason.mention",
            Self::ReasonAssigned => "issues.sidebar.reason.assigned",
            Self::ReasonReviewRequested => "issues.sidebar.reason.review-requested",
        }
    }

    fn english(self, text: &mut MessageWriter) {
        text.literal(match self {
            Self::Assignees => "Assignees",
            Self::NoOne => "No one",
            Self::AssignYourself => "assign yourself",
            Self::EditAssignees => "Edit assignees",
            Self::SaveAssignees => "Save assignees",
            Self::Labels => "Labels",
            Self::NoneYet => "None yet",
            Self::EditLabels => "Edit labels",
            Self::NoRepositoryLabels => "This repository has no labels yet.",
            Self::SaveLabels => "Save labels",
            Self::Milestone => "Milestone",
            Self::NoMilestone => "No milestone",
            Self::ChangeMilestone => "Change milestone",
            Self::SaveMilestone => "Save milestone",
            Self::Notifications => "Notifications",
            Self::Subscribe => "Subscribe",
            Self::Unsubscribe => "Unsubscribe",
            Self::NotNotifiedIssue => "You are not notified about this issue.",
            Self::NotNotifiedPull => "You are not notified about this pull request.",
            Self::Danger => "Danger",
            Self::DeleteIssue => "Delete issue",
            Self::DeletePull => "Delete pull request",
            Self::DeleteIssueConfirm => "Delete this issue for good? This cannot be undone.",
            Self::DeletePullConfirm => "Delete this pull request for good? This cannot be undone.",
            Self::ReasonManual => "You subscribed to this thread.",
            Self::ReasonComment => "You commented on this thread.",
            Self::ReasonReviewed => "You reviewed this pull request.",
            Self::ReasonAuthor => "You opened this thread.",
            Self::ReasonMention => "You were mentioned.",
            Self::ReasonAssigned => "You are assigned.",
            Self::ReasonReviewRequested => "Your review was requested.",
        });
    }
}
