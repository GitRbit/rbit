//! A conversation's comments, comment form, title editor and state badge, plus the form
//! words the issue and pull request pages share.
use super::super::fallback::{MessageFamily, MessageWriter};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ThreadMessage {
    /// State badges.
    Open,
    Closed,
    Merged,
    Draft,
    /// Shared form words.
    Title,
    Description,
    Edit,
    Save,
    Cancel,
    Delete,
    Optional,
    MarkdownSupported,
    SignIn,
    /// The conversation.
    LoadMore,
    AddComment,
    CommentPlaceholder,
    MentionSuggestions,
    CommentHint,
    LockedHint,
    CloseIssue,
    ClosePull,
    CloseNotPlanned,
    ReopenIssue,
    ReopenPull,
    Comment,
    LockConversation,
    UnlockConversation,
    /// A comment's header.
    Bot,
    Edited,
    Author,
    Reply,
    DeleteCommentConfirm,
    DeleteComment,
    NoDescription,
}

impl MessageFamily for ThreadMessage {
    fn id(self) -> &'static str {
        match self {
            Self::Open => "timeline.badge.open",
            Self::Closed => "timeline.badge.closed",
            Self::Merged => "timeline.badge.merged",
            Self::Draft => "timeline.badge.draft",
            Self::Title => "timeline.form.title",
            Self::Description => "timeline.form.description",
            Self::Edit => "timeline.form.edit",
            Self::Save => "timeline.form.save",
            Self::Cancel => "timeline.form.cancel",
            Self::Delete => "timeline.form.delete",
            Self::Optional => "timeline.form.optional",
            Self::MarkdownSupported => "timeline.form.markdown",
            Self::SignIn => "timeline.sign-in",
            Self::LoadMore => "timeline.load-more",
            Self::AddComment => "timeline.comment-form.title",
            Self::CommentPlaceholder => "timeline.comment-form.placeholder",
            Self::MentionSuggestions => "timeline.comment-form.suggestions",
            Self::CommentHint => "timeline.comment-form.hint",
            Self::LockedHint => "timeline.comment-form.locked",
            Self::CloseIssue => "timeline.comment-form.close-issue",
            Self::ClosePull => "timeline.comment-form.close-pull",
            Self::CloseNotPlanned => "timeline.comment-form.close-not-planned",
            Self::ReopenIssue => "timeline.comment-form.reopen-issue",
            Self::ReopenPull => "timeline.comment-form.reopen-pull",
            Self::Comment => "timeline.comment-form.submit",
            Self::LockConversation => "timeline.lock",
            Self::UnlockConversation => "timeline.unlock",
            Self::Bot => "timeline.comment.bot",
            Self::Edited => "timeline.comment.edited",
            Self::Author => "timeline.comment.author",
            Self::Reply => "timeline.comment.reply",
            Self::DeleteCommentConfirm => "timeline.comment.delete-confirm",
            Self::DeleteComment => "timeline.comment.delete",
            Self::NoDescription => "timeline.comment.no-description",
        }
    }

    fn english(self, text: &mut MessageWriter) {
        text.literal(match self {
            Self::Open => "Open",
            Self::Closed => "Closed",
            Self::Merged => "Merged",
            Self::Draft => "Draft",
            Self::Title => "Title",
            Self::Description => "Description",
            Self::Edit => "Edit",
            Self::Save => "Save",
            Self::Cancel => "Cancel",
            Self::Delete => "Delete",
            Self::Optional => "optional",
            Self::MarkdownSupported => "Markdown is supported",
            Self::SignIn => "Sign in",
            Self::LoadMore => "Load more",
            Self::AddComment => "Add a comment",
            Self::CommentPlaceholder => "Write a comment. Use @ for users and # for issues or pull requests.",
            Self::MentionSuggestions => "Mention suggestions",
            Self::CommentHint => "Markdown is supported. Use @name, #123 or owner/repo#123 to link a user, issue or pull request.",
            Self::LockedHint => "This conversation is locked; only collaborators can comment.",
            Self::CloseIssue => "Close issue",
            Self::ClosePull => "Close pull request",
            Self::CloseNotPlanned => "Close as not planned",
            Self::ReopenIssue => "Reopen issue",
            Self::ReopenPull => "Reopen pull request",
            Self::Comment => "Comment",
            Self::LockConversation => "Lock conversation",
            Self::UnlockConversation => "Unlock conversation",
            Self::Bot => "bot",
            Self::Edited => "edited",
            Self::Author => "Author",
            Self::Reply => "Reply",
            Self::DeleteCommentConfirm => "Delete this comment?",
            Self::DeleteComment => "Delete comment",
            Self::NoDescription => "No description provided.",
        });
    }
}
