//! Colour themes: the built-in monochrome Rbit themes and the generated tinted catalog.
//!
//! A theme only recolours the semantic tokens (`--canvas`, `--surface`, `--ink`, …), never
//! layout. The active one is `<html data-theme="SLUG">`:
//!
//! * no attribute — **System**: the built-in tokens follow the OS via `light-dark()`;
//! * `light` / `dark` — the built-in tokens pinned to one scheme (all in `app.css`);
//! * `base16-…` / `base24-…` — a [tinted-theming](https://github.com/tinted-theming) scheme,
//!   whose single small stylesheet (`assets/themes/<slug>.css`) is linked only while active.
//!
//! The choice lives in the [`COOKIE`] cookie so the server renders the right attribute and
//! stylesheet into the first byte of HTML: no flash and no blocking script. Signed-in users'
//! choices are also stored by `PreferenceService` and restored into the cookie on sign-in.
//!
//! Frontend workstream T owns this module. `catalog.rs` is generated by `npm run themes`.

#[rustfmt::skip]
mod catalog;

use std::fmt;

use axum::http::HeaderMap;
use axum_extra::extract::cookie::{Cookie, CookieJar, SameSite};

use crate::assets;

pub use catalog::SOURCE_COMMIT;

/// Cookie holding the chosen theme slug. Readable by scripts so switching is instant.
pub const COOKIE: &str = "rbit-theme";
/// The theme cookie's name from before the rename to Rbit, read when [`COOKIE`] is absent.
pub const LEGACY_COOKIE: &str = "rustit-theme";

/// How long the theme cookie lives.
const COOKIE_MAX_AGE_DAYS: i64 = 365;

/// Page backgrounds of the built-in themes, for `<meta name="theme-color">`. They must match
/// `--canvas` in `styles/app.css` (a test checks this).
pub const LIGHT_CANVAS: &str = "#f7f7f7";
pub const DARK_CANVAS: &str = "#000000";

/// Whether a theme is light or dark.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Variant {
    Light,
    Dark,
}

impl Variant {
    /// The CSS `color-scheme` keyword, also used as `data-scheme` / `data-variant`.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Light => "light",
            Self::Dark => "dark",
        }
    }
}

/// The tinted-theming specification a scheme follows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum System {
    Base16,
    Base24,
}

impl System {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Base16 => "base16",
            Self::Base24 => "base24",
        }
    }
}

/// One imported scheme.
#[derive(Debug, PartialEq, Eq)]
pub struct TintedTheme {
    /// `base16-…` or `base24-…`; `[a-z0-9-]+`.
    pub slug: &'static str,
    pub name: &'static str,
    /// Display name of the family it is grouped under (its own name when it stands alone).
    pub family: &'static str,
    pub variant: Variant,
    pub system: System,
    pub author: &'static str,
    /// The page background (`--canvas`), for `theme-color`.
    pub canvas: &'static str,
    /// The body text colour (`--ink`).
    pub ink: &'static str,
    /// The same scheme's sibling of the opposite variant ("Gruvbox dark, hard" ↔ "Gruvbox
    /// light, hard"), which the light/dark toggle switches to.
    pub counterpart: Option<&'static str>,
    /// The scheme's eight accents, base08 to base0F (red, orange, yellow, green, cyan, blue,
    /// purple, brown).
    pub swatches: [&'static str; 8],
}

/// Every tinted theme, sorted by slug.
pub fn tinted() -> &'static [TintedTheme] {
    catalog::THEMES
}

/// The tinted theme called `slug`.
pub fn find(slug: &str) -> Option<&'static TintedTheme> {
    catalog::THEMES.binary_search_by(|theme| theme.slug.cmp(slug)).ok().map(|index| &catalog::THEMES[index])
}

/// A theme a visitor can choose.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Theme {
    /// Follows the operating system's light or dark preference.
    #[default]
    System,
    Light,
    Dark,
    Tinted(&'static TintedTheme),
}

impl Theme {
    /// The built-in themes, in the order pickers list them.
    pub const BUILT_IN: [Self; 3] = [Self::System, Self::Light, Self::Dark];

    /// The theme called `slug`, if this release ships it.
    pub fn parse(slug: &str) -> Option<Self> {
        match slug {
            "system" => Some(Self::System),
            "light" => Some(Self::Light),
            "dark" => Some(Self::Dark),
            other => find(other).map(Self::Tinted),
        }
    }

    /// The theme chosen in a request's cookies; anything missing or unknown is the default.
    pub fn from_headers(headers: &HeaderMap) -> Self {
        let jar = CookieJar::from_headers(headers);
        jar.get(COOKIE).or_else(|| jar.get(LEGACY_COOKIE)).and_then(|cookie| Self::parse(cookie.value())).unwrap_or_default()
    }

    pub fn slug(self) -> &'static str {
        match self {
            Self::System => "system",
            Self::Light => "light",
            Self::Dark => "dark",
            Self::Tinted(theme) => theme.slug,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Self::System => "System",
            Self::Light => "Rbit Light",
            Self::Dark => "Rbit Dark",
            Self::Tinted(theme) => theme.name,
        }
    }

    /// Light or dark; `None` for System, which depends on the device.
    pub fn variant(self) -> Option<Variant> {
        match self {
            Self::System => None,
            Self::Light => Some(Variant::Light),
            Self::Dark => Some(Variant::Dark),
            Self::Tinted(theme) => Some(theme.variant),
        }
    }

    /// `data-theme` on `<html>`; System has none.
    pub fn attribute(self) -> Option<&'static str> {
        match self {
            Self::System => None,
            other => Some(other.slug()),
        }
    }

    /// `data-scheme` on `<html>` (`light`/`dark`); System has none.
    pub fn scheme(self) -> Option<&'static str> {
        self.variant().map(Variant::as_str)
    }

    /// The content-hashed stylesheet a tinted theme needs; built-in themes live in `app.css`.
    pub fn stylesheet(self) -> Option<String> {
        match self {
            Self::Tinted(theme) => Some(assets::url(&format!("themes/{}.css", theme.slug))),
            _ => None,
        }
    }

    /// `<meta name="theme-color">` for a pinned theme; System uses one per OS scheme.
    pub fn theme_color(self) -> Option<&'static str> {
        match self {
            Self::System => None,
            Self::Light => Some(LIGHT_CANVAS),
            Self::Dark => Some(DARK_CANVAS),
            Self::Tinted(theme) => Some(theme.canvas),
        }
    }

    /// What the header's light/dark toggle switches to: the scheme's own sibling of the other
    /// variant when it has one, otherwise the built-in theme of the other variant. System
    /// becomes Dark here; `theme-picker.js` picks the side opposite the device's scheme.
    pub fn toggled(self) -> Self {
        match self {
            Self::System | Self::Light => Self::Dark,
            Self::Dark => Self::Light,
            Self::Tinted(theme) => theme.counterpart.and_then(find).map_or(
                match theme.variant {
                    Variant::Light => Self::Dark,
                    Variant::Dark => Self::Light,
                },
                Self::Tinted,
            ),
        }
    }

    pub fn is_tinted(self) -> bool {
        matches!(self, Self::Tinted(_))
    }

    /// The cookie remembering this choice for a year, on every path. Not `HttpOnly`, so the
    /// picker can update it without a round trip; `Secure` whenever the site is on HTTPS.
    pub fn cookie(self, https: bool) -> Cookie<'static> {
        Cookie::build((COOKIE, self.slug()))
            .path("/")
            .same_site(SameSite::Lax)
            .secure(https)
            .http_only(false)
            .max_age(time::Duration::days(COOKIE_MAX_AGE_DAYS))
            .build()
    }
}

impl fmt::Display for Theme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name())
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use axum::http::{HeaderValue, header};

    use super::*;

    fn is_hex(value: &str) -> bool {
        value.len() == 7 && value.starts_with('#') && value[1..].bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
    }

    fn luminance(hex: &str) -> f64 {
        let channel = |i: usize| {
            let c = f64::from(u8::from_str_radix(&hex[i..i + 2], 16).unwrap()) / 255.0;
            if c <= 0.040_45 { c / 12.92 } else { ((c + 0.055) / 1.055).powf(2.4) }
        };
        0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5)
    }

    fn contrast(a: &str, b: &str) -> f64 {
        let (la, lb) = (luminance(a), luminance(b));
        (la.max(lb) + 0.05) / (la.min(lb) + 0.05)
    }

    #[test]
    fn catalog_is_sorted_unique_and_well_formed() {
        let themes = tinted();
        assert!(themes.len() >= 300, "the catalog imports hundreds of schemes, found {}", themes.len());
        assert!(themes.windows(2).all(|pair| pair[0].slug < pair[1].slug), "sorted by slug, without duplicates");
        let mut names = HashSet::new();
        for theme in themes {
            let prefix = format!("{}-", theme.system.as_str());
            assert!(theme.slug.starts_with(&prefix), "{} carries its system prefix", theme.slug);
            assert!(theme.slug.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-'), "{}", theme.slug);
            assert!(rbit_services::preferences::is_theme_slug(theme.slug), "{} can be stored", theme.slug);
            assert!(!theme.name.is_empty() && !theme.family.is_empty() && !theme.author.is_empty(), "{}", theme.slug);
            assert!(names.insert(theme.name.to_lowercase()), "{} is listed once", theme.name);
            assert!(is_hex(theme.canvas) && is_hex(theme.ink), "{}", theme.slug);
            assert!(theme.swatches.iter().all(|c| is_hex(c)), "{}", theme.slug);
            assert_eq!(find(theme.slug), Some(theme));
        }
    }

    #[test]
    fn counterparts_are_the_same_family_in_the_other_variant() {
        let mut paired = 0;
        for theme in tinted() {
            let Some(slug) = theme.counterpart else { continue };
            paired += 1;
            let other = find(slug).unwrap_or_else(|| panic!("{} pairs with unknown {slug}", theme.slug));
            assert_eq!(other.family, theme.family, "{} ↔ {slug}", theme.slug);
            assert_ne!(other.variant, theme.variant, "{} ↔ {slug}", theme.slug);
        }
        assert!(paired >= 100, "most families pair their light and dark schemes, found {paired}");
    }

    #[test]
    fn the_toggle_keeps_the_scheme_and_flips_the_variant() {
        let toggled = |slug: &str| Theme::parse(slug).unwrap().toggled().slug();
        assert_eq!(toggled("system"), "dark");
        assert_eq!(toggled("light"), "dark");
        assert_eq!(toggled("dark"), "light");
        for (from, to) in [
            ("base16-gruvbox-dark-hard", "base16-gruvbox-light-hard"),
            ("base16-gruvbox-light-soft", "base16-gruvbox-dark-soft"),
            ("base16-solarized-light", "base16-solarized-dark"),
            ("base24-catppuccin-latte", "base24-catppuccin-mocha"),
            ("base24-catppuccin-frappe", "base24-catppuccin-latte"),
            ("base16-rose-pine-dawn", "base16-rose-pine"),
            ("base24-tokyo-night-dark", "base24-tokyo-night-light"),
        ] {
            assert_eq!(toggled(from), to);
        }
        // Schemes without a sibling fall back to the built-in theme of the other variant.
        let lonely_dark = tinted().iter().find(|t| t.counterpart.is_none() && t.variant == Variant::Dark).unwrap();
        assert_eq!(Theme::Tinted(lonely_dark).toggled(), Theme::Light);
        let lonely_light = tinted().iter().find(|t| t.counterpart.is_none() && t.variant == Variant::Light).unwrap();
        assert_eq!(Theme::Tinted(lonely_light).toggled(), Theme::Dark);
    }

    #[test]
    fn catalog_text_is_readable_on_its_page() {
        for theme in tinted() {
            let ratio = contrast(theme.ink, theme.canvas);
            assert!(ratio >= 4.5, "{}: ink on canvas is {ratio:.2}:1", theme.slug);
            let dark = luminance(theme.canvas) < luminance(theme.ink);
            assert_eq!(dark, theme.variant == Variant::Dark, "{}: variant matches its colours", theme.slug);
        }
    }

    #[test]
    fn both_variants_and_known_families_are_present() {
        let themes = tinted();
        assert!(themes.iter().any(|t| t.variant == Variant::Light));
        assert!(themes.iter().any(|t| t.variant == Variant::Dark));
        for family in ["Catppuccin", "Gruvbox", "Tokyo Night", "Rosé Pine", "Solarized"] {
            assert!(themes.iter().filter(|t| t.family == family).count() >= 2, "{family} groups its variants");
        }
    }

    #[test]
    fn every_tinted_theme_has_its_stylesheet() {
        for theme in tinted() {
            let css = assets::read(&format!("themes/{}.css", theme.slug)).unwrap_or_else(|| panic!("{} has no stylesheet", theme.slug));
            let css = String::from_utf8_lossy(&css);
            assert!(css.contains(&format!("[data-theme=\"{}\"]{{color-scheme:{};", theme.slug, theme.variant.as_str())), "{}", theme.slug);
            assert!(css.contains(&format!("--canvas:{};", theme.canvas)), "{}", theme.slug);
        }
        let all = assets::read("themes/all.css").expect("the gallery stylesheet exists");
        assert_eq!(String::from_utf8_lossy(&all).matches("[data-theme=").count(), tinted().len());
    }

    #[test]
    fn built_in_canvas_colours_match_the_stylesheet() {
        let css = include_str!("../../styles/app.css");
        assert!(css.contains(&format!("--canvas: light-dark({LIGHT_CANVAS}, {DARK_CANVAS});")), "update LIGHT_CANVAS / DARK_CANVAS");
    }

    #[test]
    fn parses_built_in_and_tinted_slugs() {
        assert_eq!(Theme::parse("system"), Some(Theme::System));
        assert_eq!(Theme::parse("light"), Some(Theme::Light));
        assert_eq!(Theme::parse("dark"), Some(Theme::Dark));
        let first = &tinted()[0];
        assert_eq!(Theme::parse(first.slug), Some(Theme::Tinted(first)));
        for unknown in ["", "Dark", "base16-does-not-exist", "../dark", "dark "] {
            assert_eq!(Theme::parse(unknown), None, "{unknown:?}");
        }
    }

    #[test]
    fn reads_the_cookie_and_falls_back_to_system() {
        let with = |cookie: &str| {
            let mut headers = HeaderMap::new();
            headers.insert(header::COOKIE, HeaderValue::from_str(cookie).unwrap());
            Theme::from_headers(&headers)
        };
        assert_eq!(Theme::from_headers(&HeaderMap::new()), Theme::System);
        assert_eq!(with("rbit-theme=dark"), Theme::Dark);
        assert_eq!(with("other=1; rbit-theme=light; more=2"), Theme::Light);
        assert_eq!(with("rbit-theme=base24-nope"), Theme::System);
        assert_eq!(with("rustit-theme=dark"), Theme::Dark, "the cookie from before the rename");
        assert_eq!(with("rustit-theme=dark; rbit-theme=light"), Theme::Light);
        assert_eq!(with("rbit-theme=%3Cscript%3E"), Theme::System);
        let slug = tinted()[0].slug;
        assert_eq!(with(&format!("rbit-theme={slug}")).slug(), slug);
    }

    #[test]
    fn cookie_is_long_lived_lax_and_script_readable() {
        let cookie = Theme::Dark.cookie(true).to_string();
        for part in ["rbit-theme=dark", "Path=/", "SameSite=Lax", "Secure", "Max-Age=31536000"] {
            assert!(cookie.contains(part), "{cookie} has {part}");
        }
        assert!(!cookie.contains("HttpOnly"));
        assert!(!Theme::Light.cookie(false).to_string().contains("Secure"));
    }

    #[test]
    fn page_attributes_follow_the_theme() {
        assert_eq!(Theme::System.attribute(), None);
        assert_eq!(Theme::System.scheme(), None);
        assert_eq!(Theme::System.stylesheet(), None);
        assert_eq!(Theme::Dark.attribute(), Some("dark"));
        assert_eq!(Theme::Dark.theme_color(), Some(DARK_CANVAS));
        let tinted = Theme::Tinted(&tinted()[0]);
        assert_eq!(tinted.attribute(), Some(tinted.slug()));
        assert!(tinted.stylesheet().is_some_and(|url| url.starts_with(&format!("/assets/themes/{}.css?v=", tinted.slug()))));
    }
}
